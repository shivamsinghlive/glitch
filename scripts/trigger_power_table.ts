/**
 * Glitch — power & calibration of the n-of-1 hot-flash trigger test (client/src/lib/menopause.ts).
 *
 * 1. Power table: P(detect) for one real trigger on 30% of days, by base rate × rate ratio × days logged
 *    (triggerPower: Poisson counts, permutation p < 0.10/6 AND 95% CI lower bound > 1; BH ≈ its smallest-p threshold).
 * 2. Days needed for 80% power (daysNeeded, the number shown in the app).
 * 3. Null calibration of the FULL procedure: 6 independent null triggers (RR = 1), each on a random ~30%
 *    of days, 2000 permutations, Benjamini–Hochberg, CI rule — Poisson and overdispersed counts.
 * 4. Check of that BH approximation: 1 real trigger + 5 nulls through the full procedure.
 *
 * Run: pnpm power:triggers   (writes docs/trigger-power.md)
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { analyzeTriggerCounts, triggerPower, daysNeeded, poissonDraw, type TriggerKey } from "../client/src/lib/menopause";

const KEYS: TriggerKey[] = ["alcohol", "caffeine", "spicy", "late_meal", "high_stress", "warm_night"];
const SHARE = 0.3;

function mulberry32(seed: number) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
// Gamma(shape, 1) via Marsaglia–Tsang (shape ≥ 1), for gamma–Poisson (negative binomial) counts
function gammaDraw(shape: number, rand: () => number): number {
  const d = shape - 1 / 3, c = 1 / Math.sqrt(9 * d);
  for (;;) {
    let x: number, v: number;
    do { x = Math.sqrt(-2 * Math.log(rand() || 1e-12)) * Math.cos(2 * Math.PI * rand()); v = 1 + c * x; } while (v <= 0);
    v = v ** 3;
    const u = rand();
    if (Math.log(u || 1e-12) < 0.5 * x * x + d - d * v + d * Math.log(v)) return d * v;
  }
}
/** Daily count: Poisson(rate), or negative binomial with variance rate + rate²/k when k is given. */
const draw = (rate: number, rand: () => number, k?: number) => poissonDraw(k ? rate * gammaDraw(k, rand) / k : rate, rand);

/** Full procedure on simulated data; returns #significant triggers and whether the real one (alcohol) was found. */
function fullRun(days: number, base: number, rr: number, rand: () => number, k?: number, perms = 2000) {
  const labels = {} as Record<TriggerKey, boolean[]>;
  KEYS.forEach((key) => { labels[key] = Array.from({ length: days }, () => rand() < SHARE); });
  const counts = Array.from({ length: days }, (_, i) => draw(base * (labels.alcohol[i] ? rr : 1), rand, k));
  const res = analyzeTriggerCounts(counts, labels, perms);
  const sig = res.filter((r) => r.significant);
  return { nullSig: sig.filter((r) => r.trigger !== "alcohol").length, anyNull: sig.some((r) => r.trigger !== "alcohol"), realFound: sig.some((r) => r.trigger === "alcohol"), tested: res.length };
}

const pct = (x: number) => `${(100 * x).toFixed(1)}%`;
const out: string[] = [];
const log = (s = "") => { out.push(s); console.log(s); };
const t0 = Date.now();

log("# Hot-flash trigger test: power and calibration");
log();
log("Generated by `scripts/trigger_power_table.ts` (`pnpm power:triggers`). Deterministic (seeded). Method in `client/src/lib/menopause.ts`:");
log("per-trigger Poisson rate ratio with Wald 95% CI on log-RR, one-sided permutation test, Benjamini–Hochberg across tested triggers;");
log("a trigger is flagged only if q < 0.10 **and** the CI lower bound > 1. Triggers need ≥5 days with and ≥5 without.");
log();

// 1. Power table
const SIMS = 1000;
log(`## 1. Power: one real trigger on ${SHARE * 100}% of days`);
log();
log(`Probability the trigger is flagged. ${SIMS} simulations per cell, 200 permutations each, Poisson daily counts; BH approximated by its threshold for the smallest of 6 p-values, 0.10/6 (see §4). Monte-Carlo SE ≤ 1.6 points.`);
log();
log("| Base flashes/day | Rate ratio | 30 days | 60 days | 90 days |");
log("|---|---|---|---|---|");
for (const base of [1, 3, 6]) for (const rr of [1.3, 1.5, 2]) {
  const cells = [30, 60, 90].map((days) => pct(triggerPower({ baseRate: base, rateRatio: rr, triggerShare: SHARE, days, sims: SIMS })));
  log(`| ${base} | ${rr}× | ${cells.join(" | ")} |`);
}
log();

// 2. Days needed
log("## 2. Days of logging needed for 80% power");
log();
log("Smallest number of days (searched 14–180) at which power ≥ 80% (200 sims per step, as computed in the app). — = not reached within 180 days.");
log();
log("| Base flashes/day | 1.3× | 1.5× | 2× |");
log("|---|---|---|---|");
for (const base of [0.5, 1, 2, 3, 6]) {
  const cells = [1.3, 1.5, 2].map((rr) => daysNeeded({ baseRate: base, rateRatio: rr, triggerShare: SHARE }) ?? "—");
  log(`| ${base} | ${cells.join(" | ")} |`);
}
log();

// 3. Null calibration
const NULL_SIMS = 500;
log("## 3. False positives under the null (full procedure)");
log();
log(`No trigger has any effect (RR = 1). Each simulated user has 6 candidate triggers, each present on a random ~30% of days; full procedure with 2000 permutations + BH + CI rule. ${NULL_SIMS} simulated users per row.`);
log("**Family-wise** = share of users shown at least one (false) trigger; **per trigger** = share of tested triggers falsely flagged.");
log("Overdispersed rows use negative-binomial counts (variance = μ + μ²/2), closer to real symptom diaries than Poisson.");
log();
log("| Counts | Base/day | Days | Family-wise FP | Per-trigger FP |");
log("|---|---|---|---|---|");
let seed = 1;
const nullRows: { label: string; fw: number }[] = [];
for (const k of [undefined, 2]) for (const base of [1, 3, 6]) for (const days of [30, 60, 90]) {
  const rand = mulberry32(seed++);
  let fw = 0, flagged = 0, tested = 0;
  for (let s = 0; s < NULL_SIMS; s++) {
    const r = fullRun(days, base, 1, rand, k);
    if (r.anyNull) fw++;
    flagged += r.nullSig; tested += r.tested;
  }
  nullRows.push({ label: `${k ? "NB" : "Poisson"} ${base}/day ${days}d`, fw: fw / NULL_SIMS });
  log(`| ${k ? "Overdispersed (NB, k=2)" : "Poisson"} | ${base} | ${days} | ${pct(fw / NULL_SIMS)} | ${pct(flagged / Math.max(1, tested))} |`);
}
const worst = nullRows.reduce((a, b) => (b.fw > a.fw ? b : a));
log();
log(`Worst family-wise false-positive rate across rows: **${pct(worst.fw)}** (${worst.label}). Nominal BH level is 10%; the CI rule (one-sided ≈2.5%) makes the combined test conservative.`);
log();

// 4. BH approximation check
log("## 4. Check: BH approximation vs full procedure");
log();
log("Power for one real trigger tested alongside 5 null triggers through the full procedure (BH over all tested, trigger days drawn at random), vs the app's approximation (p < 0.10/6) and a naive single test (p < 0.10). 400 sims each.");
log();
log("| Base/day | Rate ratio | Days | Naive single test | App approximation (0.10/6) | Full procedure (6 triggers + BH) |");
log("|---|---|---|---|---|---|");
for (const [base, rr, days] of [[3, 1.5, 60], [1, 2, 60], [6, 1.3, 90]] as const) {
  const rand = mulberry32(1000 + base * 10 + days);
  let found = 0;
  for (let s = 0; s < 400; s++) if (fullRun(days, base, rr, rand, undefined, 500).realFound) found++;
  const pw = (tests: number) => pct(triggerPower({ baseRate: base, rateRatio: rr, triggerShare: SHARE, days, sims: 400, tests }));
  log(`| ${base} | ${rr}× | ${days} | ${pw(1)} | ${pw(6)} | ${pct(found / 400)} |`);
}
log();
log("## Caveats");
log();
log("- Simulations assume days are independent; real symptoms carry over between days (autocorrelation), which the permutation test does not model.");
log("- Trigger days are assumed to be logged accurately; missed logs dilute the effect and lower power.");
log("- A flagged trigger is an association in one person's logs, not proof of cause.");
log();
log(`_Runtime ${((Date.now() - t0) / 1000).toFixed(1)} s._`);

mkdirSync("docs", { recursive: true });
writeFileSync("docs/trigger-power.md", out.join("\n") + "\n");
console.error("wrote docs/trigger-power.md");
